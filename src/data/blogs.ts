import { getBlogBySlug as getDynamicBlogBySlug } from "@/lib/blogStorage";

export function getBlogBySlug(slug: string): BlogPost | undefined {
  const dynamicPost = getDynamicBlogBySlug(slug);
  if (dynamicPost) {
    return {
      slug: dynamicPost.slug,
      title: dynamicPost.title,
      excerpt: dynamicPost.excerpt,
      category: dynamicPost.category,
      date: new Date(dynamicPost.publishedAt || dynamicPost.createdAt).toLocaleDateString("en-US", {
        month: "long",
        day: "numeric",
        year: "numeric",
      }),
      readTime: dynamicPost.readTime,
      author: dynamicPost.author,
      image: dynamicPost.featuredImage,
      content: [dynamicPost.content],
    };
  }
  return BLOGS.find((b) => b.slug === slug);
}

